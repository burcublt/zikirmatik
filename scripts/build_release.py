#!/usr/bin/env python3
"""Validate local release inputs, then build a local artifact. Never uploads."""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SAMPLE_PUBLISHER = '3940256099942544'
APP_ID = re.compile(r'^ca-app-pub-(\d{16})~\d{10}$')
UNIT_ID = re.compile(r'^ca-app-pub-(\d{16})/\d{10}$')

def read_properties(path):
    if not path.is_file():
        return {}
    result = {}
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.strip() and not line.lstrip().startswith(('#', '!')) and '=' in line:
            key, value = line.split('=', 1)
            result[key.strip()] = value.strip()
    return result

def validate(platform, values, root=ROOT):
    errors = []
    prefix = platform.upper()
    identity_key = 'ANDROID_APPLICATION_ID' if platform == 'android' else 'IOS_BUNDLE_ID'
    identity = values.get(identity_key, '')
    pattern = r'[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+' if platform == 'android' else r'[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+'
    if not isinstance(identity, str) or not re.fullmatch(pattern, identity) or identity.startswith('com.example.'):
        errors.append(f'{identity_key}: benzersiz gerçek uygulama kimliği gerekli.')
    publisher = None
    for suffix, pattern in [('APP_ID', APP_ID), ('NATIVE', UNIT_ID), ('BANNER', UNIT_ID)]:
        key = f'ADMOB_{prefix}_{suffix}'
        value = values.get(key, '')
        match = pattern.fullmatch(value) if isinstance(value, str) else None
        if not match or match.group(1) == SAMPLE_PUBLISHER:
            errors.append(f'{key}: gerçek AdMob kimliği gerekli; örnek kimlik kabul edilmez.')
        elif publisher is None:
            publisher = match.group(1)
        elif publisher != match.group(1):
            errors.append(f'{key}: yayıncı hesabı App ID ile eşleşmiyor.')
    if platform == 'android':
        props = read_properties(root / 'android/key.properties')
        missing = [key for key in ['storeFile','storePassword','keyAlias','keyPassword'] if not props.get(key)]
        if missing:
            errors.append('android/key.properties: eksik alanlar: ' + ', '.join(missing))
        elif props['keyAlias'].lower() == 'androiddebugkey':
            errors.append('Android yayın imzası debug anahtarı olamaz.')
        else:
            keyfile = Path(props['storeFile']).expanduser()
            if not keyfile.is_absolute():
                keyfile = root / 'android' / keyfile
            if not keyfile.is_file():
                errors.append('android/key.properties: storeFile bulunamadı.')
    return errors

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--platform', required=True, choices=['android','ios'])
    parser.add_argument('--config', type=Path, default=ROOT / 'config/release.local.json')
    parser.add_argument('--check-only', action='store_true')
    parser.add_argument('--flutter', default=os.environ.get('FLUTTER_BIN', 'flutter'))
    args = parser.parse_args(argv)
    try:
        values = json.loads(args.config.read_text(encoding='utf-8'))
        if not isinstance(values, dict):
            raise ValueError('JSON object required')
    except (OSError, ValueError):
        print('Yayın ayarları okunamadı. config/release.example.json dosyasından release.local.json oluşturun.', file=sys.stderr)
        return 2
    errors = validate(args.platform, values)
    if errors:
        print('Yayın paketi hazırlanmadı:', file=sys.stderr)
        for error in errors:
            print('- ' + error, file=sys.stderr)
        return 2
    if args.check_only:
        print('Yayın kimliklerinin biçimi ve yerel dosyalar doğrulandı. Hesap sahipliği ve imza geçerliliği bu kontrolle doğrulanmaz.')
        return 0
    flutter = shutil.which(args.flutter)
    if not flutter:
        print('Flutter bulunamadı. --flutter ile Flutter çalıştırılabilir dosyasını belirtin.', file=sys.stderr)
        return 2
    if args.platform == 'ios':
        generated = ROOT / 'ios/Flutter/Release.generated.xcconfig'
        generated.write_text('// Generated by scripts/build_release.py; do not edit.\n'
          + f'ZIKIRMATIK_BUNDLE_ID = {values["IOS_BUNDLE_ID"]}\n'
          + f'ADMOB_IOS_APP_ID = {values["ADMOB_IOS_APP_ID"]}\n', encoding='utf-8')
    command = [flutter, 'build', 'appbundle' if args.platform == 'android' else 'ipa', '--release',
               '--dart-define-from-file=' + str(args.config.resolve())]
    build_environment = dict(os.environ)
    if args.platform == 'ios':
        build_environment['BYPASS_PERMISSION_LOCATION_ALWAYS'] = '1'
    return subprocess.run(command, cwd=ROOT, env=build_environment).returncode

if __name__ == '__main__':
    sys.exit(main())
